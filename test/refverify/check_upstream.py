"""C1.5.4 — the Merkle and signed-note code in refverify passes the same RFC
6962 and C2SP vectors as C1.3.3-C1.3.4:

- published MTH values (Trillian/crpt go-merkle rfc6962_test.go, excerpt saved
  in evidence/M1.5/*/upstream/rfc6962-merkle.md);
- the signed-note example from c2sp.org/signed-note (vkey + note);
- note key-ID derivation per signed-note.md;
- inclusion proofs for every tree size 1..64 and every leaf, generated by an
  independent recursive transcription of RFC 6962 PATH (below, not imported
  from refverify), verified by refverify.mlog;
- malformed proofs and checkpoints are rejected.
"""
import base64
import hashlib
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "ref", "python"))

H = hashlib.sha256


def h(b):
    return H(b).digest()


# --- independent RFC 6962 transcription (test side, NOT refverify) ----------
def leaf(d):
    return h(b"\x00" + d)


def node(l, r):
    return h(b"\x01" + l + r)


def mth(ds):
    n = len(ds)
    if n == 0:
        return h(b"")
    if n == 1:
        return leaf(ds[0])
    k = 1 << (n.bit_length() - 1)
    if k == n:
        k >>= 1
    return node(mth(ds[:k]), mth(ds[k:]))


def path(m, ds):
    n = len(ds)
    if n == 1:
        return []
    k = 1 << (n.bit_length() - 1)
    if k == n:
        k >>= 1
    if m < k:
        return path(m, ds[:k]) + [mth(ds[k:])]
    return path(m - k, ds[k:]) + [mth(ds[:k])]


def main() -> int:
    from cryptography.hazmat.primitives.asymmetric.ed25519 import (
        Ed25519PrivateKey, Ed25519PublicKey)
    from refverify import mlog, note

    fails = []

    # --- published MTH values ---------------------------------------------
    cases = [
        ([], "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"),
        ([b""], "6e340b9cffb37a989ca544e6bb780a2c78901d3fb33738768511a30617afa01d"),
        ([b"L123456"], "395aa064aa4c29f7010acfe3f25db9485bbd4b91897b6ad7ad547639252b4d56"),
    ]
    for ds, want in cases:
        got = mlog.mth(list(map(mlog.leaf_hash, ds))) if ds else mlog.mth([])
        # For input vectors the leaves are the raw data hashed with 0x00
        # prefix; refverify.mlog.mth takes leaf hashes of leaf data.
        if got.hex() != want:
            fails.append(f"MTH({ds!r}) = {got.hex()}, want {want}")
    if mlog.node_hash(b"N123", b"N456").hex() != \
            "aa217fe888e47007fa15edab33c2b492a722cb106c64667fc2b044444de66bbb":
        fails.append("node_hash published value mismatch")

    # --- inclusion proofs, all sizes 1..64, every leaf ---------------------
    verified = 0
    for size in range(1, 65):
        ds = [bytes([size, i]) for i in range(size)]
        leaves = [h(b"\x00" + d) for d in ds]
        root = mth(ds)
        if root != mlog.mth(leaves):
            fails.append(f"size {size}: refverify mth disagrees with RFC transcription")
            break
        for i in range(size):
            p = path(i, ds)
            if not mlog.verify_inclusion(leaves[i], i, size, p, root):
                fails.append(f"size {size} leaf {i}: valid proof rejected")
            else:
                verified += 1
            # corrupt cases
            if p:
                bad = p[:-1] + [bytes(32)]
                if mlog.verify_inclusion(leaves[i], i, size, bad, root):
                    fails.append(f"size {size} leaf {i}: corrupted proof accepted")
                if mlog.verify_inclusion(leaves[i], i, size, p[:-1], root):
                    fails.append(f"size {size} leaf {i}: truncated proof accepted")
            if mlog.verify_inclusion(leaves[i], size, size, p, root):
                fails.append(f"size {size}: out-of-range index accepted")
            if mlog.verify_inclusion(h(b"!"), i, size, p, root):
                fails.append(f"size {size} leaf {i}: wrong leaf accepted")
    print(f"  inclusion: {verified} proofs verified across sizes 1..64")

    # --- C2SP signed-note published vector --------------------------------
    vkey = "example.com/foo+530d903a+AekyeRrm56hApGFkyQR4ZCbV54Id2LKaANYcrnKv3U2k"
    note_text = (b"This is an example message.\n\n"
                 b"\xe2\x80\x94 example.com/foo "
                 b"Uw2QOkn8srV1yJGh2VYRlL1Tnagv1YEq6TfXppzi2ONncAlTgK7Ztg1ERYNZX"
                 b"sYjOBH3mFXmRKuwHjG1Yu72IneyaQM=\n")
    name, kid, keymat = note.parse_vkey(vkey)
    if name != b"example.com/foo" or kid != 0x530D903A:
        fails.append(f"vkey parse: {name} {kid:#x}")
    if keymat[0] != 0x01 or len(keymat) != 33:
        fails.append("vkey key material malformed")
    pub = keymat[1:]
    want_kid = int.from_bytes(hashlib.sha256(
        b"example.com/foo" + b"\x0a" + b"\x01" + pub).digest()[:4], "big")
    if want_kid != 0x530D903A:
        fails.append(f"note key id derivation {want_kid:#x} != 0x530d903a")
    if note.note_key_id(b"example.com/foo", 0x01, pub) != 0x530D903A:
        fails.append("refverify note_key_id disagrees")

    text, sigs = note.parse(note_text)
    if text != b"This is an example message.\n" or len(sigs) != 1:
        fails.append("note parse wrong")
    else:
        s = sigs[0]
        if s.name != b"example.com/foo" or s.key_id != 0x530D903A:
            fails.append(f"sig parse: {s.name} {s.key_id:#x}")
        Ed25519PublicKey.from_public_bytes(pub).verify(s.sig, text)

    # known-key bad signature must reject the whole note: corrupt one base64
    # char inside the signature bytes (after the 4-byte key id) while keeping
    # the encoding valid.
    bad_sig_note = note_text[:-6] + b"B" + note_text[-5:]
    t2, s2 = note.parse(bad_sig_note)
    try:
        Ed25519PublicKey.from_public_bytes(pub).verify(s2[0].sig, t2)
        fails.append("corrupted note signature still verifies")
    except Exception:
        pass

    # --- tlog-checkpoint round-trip with a fresh key ----------------------
    priv = Ed25519PrivateKey.generate()
    pub2 = priv.public_key().public_bytes_raw()
    origin = b"countersign.dev/log/01JTEST"
    root_hash = h(b"root")
    body = origin + b"\n" + b"20852163\n" + base64.b64encode(root_hash) + b"\n"
    kid2 = note.note_key_id(origin, 0x01, pub2)
    sig = priv.sign(body)
    cp = body + b"\n\xe2\x80\x94 " + origin + b" " + \
        base64.b64encode(kid2.to_bytes(4, "big") + sig) + b"\n"
    o2, size2, root2, _ext = note.parse_checkpoint_body(note.parse(cp)[0])
    if o2 != origin or size2 != 20852163 or root2 != root_hash:
        fails.append("checkpoint body parse wrong")
    verified = note.verify_text(
        note.parse(cp)[0], note.parse(cp)[1],
        {origin: [(kid2, pub2, "log")]})
    if verified != ["log"]:
        fails.append(f"checkpoint verify: {verified}")

    # unsigned / tampered checkpoint must not verify
    tampered = cp.replace(b"20852163", b"20852164")
    t3, s3 = note.parse(tampered)
    try:
        Ed25519PublicKey.from_public_bytes(pub2).verify(s3[0].sig, t3)
        fails.append("tampered checkpoint verifies")
    except Exception:
        pass
    if note.verify_text(t3, s3, {origin: [(kid2, pub2, "log")]}):
        fails.append("tampered checkpoint accepted by verify_text")

    for f_ in fails:
        print(f"  {f_}")
    if fails:
        print(f"C1.5.4: {len(fails)} failure(s)")
        return 1
    print("C1.5.4: RFC 6962 and C2SP vectors pass")
    return 0


if __name__ == "__main__":
    sys.exit(main())
